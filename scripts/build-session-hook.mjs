import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";
import { build } from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = path.join(root, "plugins/codex/scripts/session-lifecycle-hook.mjs");
const licenses = ["web-tree-sitter", "tree-sitter-bash"].map((name) =>
  `${name}:\n${fs.readFileSync(path.join(root, "node_modules", name, "LICENSE"), "utf8").trim()}`
).join("\n\n");
const result = await build({
  absWorkingDir: root,
  entryPoints: ["plugins/codex/scripts/session-lifecycle-hook.source.mjs"],
  outfile: output,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node18.18",
  write: false,
  minify: true,
  // Complete dependency license texts are included in the banner below.
  legalComments: "none",
  banner: { js: `// Generated by npm run build:session-hook. Edit the .source.mjs and shell-env.mjs files.\n/*!\n${licenses}\n*/` },
  external: ["./lib/*"],
  plugins: [{
    name: "embedded-wasm",
    setup(build) {
      build.onLoad({ filter: /\.wasm$/ }, ({ path: wasmPath }) => {
        const encoded = gzipSync(fs.readFileSync(wasmPath), { level: 9 }).toString("base64");
        return {
          loader: "js",
          contents: `import { gunzipSync } from 'node:zlib'; export default gunzipSync(Buffer.from('${encoded}', 'base64'));`
        };
      });
    }
  }]
});
const generated = result.outputFiles[0].contents;
if (process.argv.includes("--check")) {
  if (!fs.existsSync(output) || !fs.readFileSync(output).equals(generated)) {
    throw new Error("Session hook bundle is stale. Run npm run build:session-hook.");
  }
  process.stdout.write("Session hook bundle matches its pinned sources.\n");
} else {
  fs.writeFileSync(output, generated);
}
